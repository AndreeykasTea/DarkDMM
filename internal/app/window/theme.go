package window

import "github.com/SpaiR/imgui-go"

func rgba(r, g, b int, a float32) imgui.Vec4 {
	return imgui.Vec4{X: float32(r) / 255, Y: float32(g) / 255, Z: float32(b) / 255, W: a}
}

// setDefaultTheme applies the DarkDMM theme: dark navy background with blue accents.
func (w *Window) setDefaultTheme() {
	imgui.StyleColorsDark()

	s := imgui.CurrentStyle()
	s.SetWindowBorderSize(1)
	s.SetChildBorderSize(0)
	s.SetScrollbarSize(10)
	s.SetTabRounding(4)
	s.SetWindowRounding(4)
	s.SetScrollbarRounding(4)
	s.SetPopupRounding(4)
	s.SetFrameRounding(3)

	var (
		bgDeep   = rgba(10, 15, 26, 1)
		bg       = rgba(14, 21, 34, 1)
		bgRaised = rgba(20, 30, 48, 1)
		frame    = rgba(24, 37, 58, 1)
		frameHov = rgba(34, 57, 90, 1)
		frameAct = rgba(28, 49, 80, 1)
		accent   = rgba(61, 139, 255, 1)
		accentHi = rgba(106, 169, 255, 1)
		button   = rgba(30, 51, 84, 1)
		buttonHv = rgba(42, 74, 120, 1)
		buttonAc = rgba(34, 64, 106, 1)
		border   = rgba(36, 52, 79, .65)
	)

	s.SetColor(imgui.StyleColorText, rgba(230, 237, 247, 1))
	s.SetColor(imgui.StyleColorTextDisabled, rgba(107, 122, 144, 1))
	s.SetColor(imgui.StyleColorWindowBg, bg)
	s.SetColor(imgui.StyleColorChildBg, imgui.Vec4{})
	s.SetColor(imgui.StyleColorPopupBg, rgba(19, 29, 46, .97))
	s.SetColor(imgui.StyleColorBorder, border)
	s.SetColor(imgui.StyleColorBorderShadow, imgui.Vec4{W: 0.24})
	s.SetColor(imgui.StyleColorFrameBg, frame)
	s.SetColor(imgui.StyleColorFrameBgHovered, frameHov)
	s.SetColor(imgui.StyleColorFrameBgActive, frameAct)
	s.SetColor(imgui.StyleColorTitleBg, bgDeep)
	s.SetColor(imgui.StyleColorTitleBgActive, rgba(15, 27, 45, 1))
	s.SetColor(imgui.StyleColorTitleBgCollapsed, rgba(10, 15, 26, .75))
	s.SetColor(imgui.StyleColorMenuBarBg, rgba(13, 21, 34, 1))
	s.SetColor(imgui.StyleColorScrollbarBg, rgba(10, 15, 26, .6))
	s.SetColor(imgui.StyleColorScrollbarGrab, rgba(42, 65, 102, 1))
	s.SetColor(imgui.StyleColorScrollbarGrabHovered, rgba(53, 84, 131, 1))
	s.SetColor(imgui.StyleColorScrollbarGrabActive, rgba(63, 102, 160, 1))
	s.SetColor(imgui.StyleColorCheckMark, rgba(79, 163, 255, 1))
	s.SetColor(imgui.StyleColorSliderGrab, accent)
	s.SetColor(imgui.StyleColorSliderGrabActive, accentHi)
	s.SetColor(imgui.StyleColorButton, button)
	s.SetColor(imgui.StyleColorButtonHovered, buttonHv)
	s.SetColor(imgui.StyleColorButtonActive, buttonAc)
	s.SetColor(imgui.StyleColorHeader, button)
	s.SetColor(imgui.StyleColorHeaderHovered, rgba(40, 70, 112, 1))
	s.SetColor(imgui.StyleColorHeaderActive, buttonAc)
	s.SetColor(imgui.StyleColorSeparator, border)
	s.SetColor(imgui.StyleColorSeparatorHovered, rgba(61, 139, 255, .6))
	s.SetColor(imgui.StyleColorSeparatorActive, accent)
	s.SetColor(imgui.StyleColorResizeGrip, rgba(30, 51, 84, .8))
	s.SetColor(imgui.StyleColorResizeGripHovered, rgba(61, 139, 255, .7))
	s.SetColor(imgui.StyleColorResizeGripActive, accent)
	s.SetColor(imgui.StyleColorTab, rgba(18, 29, 47, 1))
	s.SetColor(imgui.StyleColorTabHovered, buttonHv)
	s.SetColor(imgui.StyleColorTabActive, rgba(30, 58, 99, 1))
	s.SetColor(imgui.StyleColorTabUnfocused, rgba(14, 22, 37, 1))
	s.SetColor(imgui.StyleColorTabUnfocusedActive, rgba(23, 42, 69, 1))
	s.SetColor(imgui.StyleColorDockingPreview, rgba(61, 139, 255, .7))
	s.SetColor(imgui.StyleColorDockingEmptyBg, bgDeep)
	s.SetColor(imgui.StyleColorPlotLines, accent)
	s.SetColor(imgui.StyleColorPlotLinesHovered, accentHi)
	s.SetColor(imgui.StyleColorPlotHistogram, accent)
	s.SetColor(imgui.StyleColorPlotHistogramHovered, accentHi)
	s.SetColor(imgui.StyleColorTableHeaderBg, bgRaised)
	s.SetColor(imgui.StyleColorTableBorderStrong, border)
	s.SetColor(imgui.StyleColorTableBorderLight, rgba(36, 52, 79, .35))
	s.SetColor(imgui.StyleColorTableRowBg, imgui.Vec4{})
	s.SetColor(imgui.StyleColorTableRowBgAlt, rgba(120, 160, 255, .05))
	s.SetColor(imgui.StyleColorTextSelectedBg, rgba(47, 93, 158, .6))
	s.SetColor(imgui.StyleColorDragDropTarget, accent)
	s.SetColor(imgui.StyleColorNavHighlight, imgui.Vec4{})
	s.SetColor(imgui.StyleColorNavWindowingHighlight, imgui.Vec4{})
	s.SetColor(imgui.StyleColorNavWindowingDimBg, imgui.Vec4{})
	s.SetColor(imgui.StyleColorModalWindowDimBg, rgba(5, 10, 20, .6))
}
